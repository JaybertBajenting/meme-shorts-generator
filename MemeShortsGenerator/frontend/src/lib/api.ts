import axios from "axios";

// In dev, Vite proxies /api -> :5180. In prod the SPA is served by the API itself,
// so relative URLs work in both.
export const http = axios.create({ baseURL: "/" });

export type JobState = "queued" | "running" | "paused" | "done" | "failed";
export type UploadState = "none" | "uploading" | "scheduled" | "uploaded" | "failed";
export type ReviewState = "none" | "pending" | "approved" | "rejected";

/** Per-destination publish state for the non-YouTube platforms. */
export interface PlatformStatus {
  state: UploadState;
  postId?: string | null;
  url?: string | null;
  error?: string | null;
  publishAt?: string | null;
}

export interface Job {
  id: string;
  topic: string;
  channelId: string;
  autoGenerated: boolean;
  createdAt: string;
  state: JobState;
  stage: string;
  percent: number;
  error?: string | null;
  title?: string | null;
  youTubeTitle?: string | null;
  youTubeDescription?: string | null;
  youTubeTags?: string[] | null;
  hasVideo: boolean;
  hasThumbnail: boolean;
  review: ReviewState;
  upload: UploadState;
  youTubeVideoId?: string | null;
  publishAt?: string | null;
  uploadError?: string | null;
  facebook: PlatformStatus;
  instagram: PlatformStatus;
}

export interface Health {
  tts: string;
  captions: string;
  panels: string;
  elevenLabsConfigured: boolean;
  uploadEnabled: boolean;
  uploadConfigured: boolean;
  autoUpload: boolean;
  facebookConfigured: boolean;
  instagramConfigured: boolean;
  /** Credentials saved but the platform is switched off — approvals will skip it. */
  facebookOffWithCreds: boolean;
  instagramOffWithCreds: boolean;
}

export interface MetaVerifyResult {
  platform: string;
  ok: boolean;
  message: string;
}

/** One platform's saved credentials. The token is never sent back in full — only a masked tail. */
export interface MetaPlatformSettings {
  enabled: boolean;
  pageId?: string;
  igUserId?: string;
  tokenSet: boolean;
  tokenMasked: string;
  usable: boolean;
  savedInApp: boolean;
}

export interface MetaSettings {
  facebook: MetaPlatformSettings;
  instagram: MetaPlatformSettings;
}

export interface Channel {
  id: string;
  name: string;
  contentType: string;
}

export const api = {
  health: () => http.get<Health>("/api/health").then((r) => r.data),
  channels: () => http.get<Channel[]>("/api/channels").then((r) => r.data),
  jobs: () => http.get<Job[]>("/api/jobs").then((r) => r.data),
  job: (id: string) => http.get<Job>(`/api/jobs/${id}`).then((r) => r.data),
  calendar: () => http.get<Job[]>("/api/calendar").then((r) => r.data),

  generate: (body: { topic: string; format?: string | null; channel?: string | null }) =>
    http.post<{ id: string }>("/api/generate", body).then((r) => r.data),

  /** Read the words baked into an image, to prefill the post text. */
  ocr: (image: File) => {
    const form = new FormData();
    const ext =
      { "image/jpeg": "jpg", "image/webp": "webp", "image/gif": "gif" }[image.type] ?? "png";
    form.append("image", image, image.name?.includes(".") ? image.name : `post.${ext}`);
    return http
      .post<{ text: string; available: boolean }>("/api/ocr", form)
      .then((r) => r.data);
  },

  /**
   * Repost: you supply the post. Multipart rather than JSON because it carries the image —
   * axios sets the boundary itself, so do NOT hand it a Content-Type here.
   */
  generateRepost: (body: {
    text: string;
    image?: File | null;
    title?: string | null;
    channel?: string | null;
  }) => {
    const form = new FormData();
    form.append("text", body.text);
    if (body.image) {
      // ALWAYS send an explicit filename. A clipboard File can carry an empty name, and an
      // empty `filename=""` part does not bind as a file server-side at all — the request
      // still succeeded and produced a video with no picture in it, which is worse than an
      // error. The extension comes from the MIME type, which a paste always sets.
      const ext =
        { "image/jpeg": "jpg", "image/webp": "webp", "image/gif": "gif" }[body.image.type] ?? "png";
      const name = body.image.name?.includes(".") ? body.image.name : `post.${ext}`;
      form.append("image", body.image, name);
    }
    if (body.title) form.append("title", body.title);
    if (body.channel) form.append("channel", body.channel);
    return http.post<{ id: string }>("/api/generate/repost", form).then((r) => r.data);
  },

  /**
   * List short: a run of pictures with one spoken line each. Picture i is paired with line i,
   * so the order the files are appended in IS the order they appear on screen.
   */
  generateList: (body: {
    images: File[];
    lines: string;
    title?: string | null;
    mascot?: File | null;
    channel?: string | null;
  }) => {
    const form = new FormData();
    form.append("lines", body.lines);
    body.images.forEach((img, i) => {
      // Always send an explicit filename — a clipboard File can carry an empty name, and an
      // empty `filename=""` part does not bind as a file server-side at all.
      const ext =
        { "image/jpeg": "jpg", "image/webp": "webp", "image/gif": "gif" }[img.type] ?? "png";
      form.append("images", img, img.name?.includes(".") ? img.name : `item_${i}.${ext}`);
    });
    if (body.mascot) form.append("mascot", body.mascot, body.mascot.name || "mascot.png");
    if (body.title) form.append("title", body.title);
    if (body.channel) form.append("channel", body.channel);
    return http.post<{ id: string }>("/api/generate/list", form).then((r) => r.data);
  },

  /**
   * Ask Codex for a list short and stage its pictures WITHOUT rendering. Commons finds a good
   * match about three times in five, so the draft is checked before three minutes of rendering
   * are spent on it.
   */
  listDraft: (body: { topic?: string | null; channel?: string | null }) =>
    http
      .post<{
        id: string;
        title: string;
        items: {
          text: string;
          term: string;
          file: string | null;
          credit: string | null;
          /** Commons page title — identifies the picture, so repeats can be avoided. */
          source: string | null;
          url: string | null;
        }[];
      }>("/api/list/draft", body)
      .then((r) => r.data),

  /**
   * Re-search one line's picture, leaving the rest of the draft alone. `exclude` carries the
   * Commons titles the other lines are using, so a swap cannot land on a picture already on
   * screen elsewhere in the same video.
   */
  listDraftImage: (id: string, body: { index: number; term: string; exclude?: string[] }) =>
    http
      .post<{
        file: string | null;
        credit?: string | null;
        source?: string | null;
        url?: string | null;
        message?: string;
      }>(`/api/list/draft/${id}/image`, body)
      .then((r) => r.data),

  listDraftConfirm: (
    id: string,
    body: {
      title?: string | null;
      channel?: string | null;
      items: { text: string; file: string | null; credit: string | null }[];
    },
  ) => http.post<{ id: string }>(`/api/list/draft/${id}/confirm`, body).then((r) => r.data),

  generateAuto: (body: { count: number; format?: string | null; channel?: string | null }) =>
    http
      .post<{ count: number; channel: string; jobs: { id: string; topic: string }[] }>(
        "/api/generate/auto",
        body,
      )
      .then((r) => r.data),

  approve: (id: string) => http.post<Job>(`/api/jobs/${id}/approve`).then((r) => r.data),
  reject: (id: string) => http.post<Job>(`/api/jobs/${id}/reject`).then((r) => r.data),
  upload: (id: string) => http.post<Job>(`/api/jobs/${id}/upload`).then((r) => r.data),
  cancelUnfinished: () =>
    http.delete<{ deleted: number }>("/api/jobs/unfinished").then((r) => r.data),
  pauseGeneration: () =>
    http.post<{ paused: boolean; affected: number }>("/api/generation/pause").then((r) => r.data),
  resumeGeneration: () =>
    http.post<{ paused: boolean; resumed: number }>("/api/generation/resume").then((r) => r.data),

  // Re-run the Google OAuth consent (opens a browser on the server machine). Use when the
  // cached token has expired/been revoked. Returns { ok, message }.
  authorize: () =>
    http.post<{ ok: boolean; message: string }>("/api/youtube/authorize").then((r) => r.data),

  // Resolve the configured Facebook/Instagram tokens to the accounts they control. Posts nothing.
  verifyMeta: () =>
    http
      .post<{ ok: boolean; results: MetaVerifyResult[] }>("/api/meta/verify")
      .then((r) => r.data),

  voiceSettings: () =>
    http
      .get<{ voiceId: string; speechRate: number; savedInApp: boolean }>("/api/settings/voice")
      .then((r) => r.data),
  saveVoiceSettings: (body: { voiceId?: string; speechRate?: number }) =>
    http.post<{ voiceId: string; speechRate: number }>("/api/settings/voice", body).then((r) => r.data),
  resetVoiceSettings: () =>
    http.post<{ voiceId: string }>("/api/settings/voice/reset").then((r) => r.data),

  /** Re-render a job with the current voice, reusing its script and artwork. */
  revoice: (id: string) => http.post<Job>(`/api/jobs/${id}/revoice`).then((r) => r.data),

  metaSettings: () => http.get<MetaSettings>("/api/settings/meta").then((r) => r.data),

  // Omit token (or send blank) to keep the stored one.
  saveMetaSettings: (body: {
    facebook?: { enabled?: boolean; pageId?: string; token?: string };
    instagram?: { enabled?: boolean; igUserId?: string; token?: string };
  }) => http.post<{ ok: boolean }>("/api/settings/meta", body).then((r) => r.data),

  resetMetaSettings: (platform?: "facebook" | "instagram") =>
    http
      .post<{ ok: boolean }>(`/api/settings/meta/reset${platform ? `?platform=${platform}` : ""}`)
      .then((r) => r.data),

  settings: () =>
    http
      .get<{
        autoApprove: boolean;
        generationPaused: boolean;
        channel: string | null;
        ocrAutofill: boolean;
      }>("/api/settings")
      .then((r) => r.data),
  /** Whether pasting a picture should prefill the text box. Off by default. */
  setOcrAutofill: (enabled: boolean) =>
    http
      .post<{ ocrAutofill: boolean }>("/api/settings/ocr-autofill", { enabled })
      .then((r) => r.data),
  setAutoApprove: (enabled: boolean) =>
    http
      .post<{ autoApprove: boolean }>("/api/settings/auto-approve", { enabled })
      .then((r) => r.data),
  /** Remember which mode the Generate tab opens on, across tab switches and restarts. */
  setChannel: (channel: string) =>
    http.post<{ channel: string | null }>("/api/settings/channel", { channel }).then((r) => r.data),
};

export const videoUrl = (id: string) => `/api/jobs/${id}/video`;
export const thumbnailUrl = (id: string) => `/api/jobs/${id}/thumbnail`;
